def inline(s):
    s = esc(s)
    s = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", s)
    s = re.sub(r"\[(.+?)\]\((.+?)\)", r'<a class="inl" href="\2">\1</a>', s)
    return s


def md(text):
    out = []
    for block in [b.strip() for b in text.strip().split("\n\n") if b.strip()]:
        lines = block.split("\n")
        if block.startswith("## "):
            out.append("<h2>%s</h2>" % inline(block[3:]))
        elif all(l.startswith("- ") for l in lines):
            out.append("<ul>%s</ul>" % "".join("<li>%s</li>" % inline(l[2:]) for l in lines))
        elif all(re.match(r"\d+\. ", l) for l in lines):
            out.append("<ol style=\"margin:0 0 18px 22px\">%s</ol>" % "".join("<li>%s</li>" % inline(re.sub(r"^\d+\. ", "", l)) for l in lines))
        elif block.startswith("> "):
            out.append('<div class="tip"><p>%s</p></div>' % inline(" ".join(l[2:] if l.startswith("> ") else l for l in lines)))
        else:
            out.append("<p>%s</p>" % inline(" ".join(lines)))
    return "\n".join(out)


