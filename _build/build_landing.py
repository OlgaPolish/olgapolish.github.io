def render(pg, lang):
    u = UI[lang]
    a = pg[lang]
    langs = [l2 for l2 in ("uk", "ru") if l2 in pg]
    url = B.SITE + B.PATHS[lang] + a["slug"]
    alts = {l2: B.SITE + B.PATHS[l2] + pg[l2]["slug"] for l2 in langs}
    hdr_alt = {l2: "/" + B.PATHS[l2] + pg[l2]["slug"] for l2 in langs}
    hdr_alt.setdefault("de", "/")
    svc = {
        "@context": "https://schema.org", "@type": "Service",
        "name": a["service"], "description": a["desc"], "inLanguage": lang, "url": url,
        "provider": {"@id": B.SITE + "#business"},
        "areaServed": {"@type": "Country", "name": "Deutschland"},
        "offers": {"@type": "Offer", "price": 450, "priceCurrency": "EUR"},
    }
    crumbs = {"@context": "https://schema.org", "@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": u["home"], "item": B.SITE + B.PATHS[lang]},
        {"@type": "ListItem", "position": 2, "name": a["h1"], "item": url}]}
    extra = '<meta property="og:type" content="website">\n<script type="application/ld+json">%s</script>\n<script type="application/ld+json">%s</script>\n' % (
        json.dumps(svc, ensure_ascii=False), json.dumps(crumbs, ensure_ascii=False))
    o = [BL.head(lang, a["seo_title"], a["desc"], url, alts, extra, "images/case-feinschliff.jpg"),
         B.header_html(lang, home=False, alt_paths=hdr_alt)]
    o.append('<main>\n<article class="post">\n')
    o.append('<nav class="crumbs" aria-label="Breadcrumb"><a href="/%s">%s</a></nav>\n' % (B.PATHS[lang], esc(u["home"])))
    o.append('<h1>%s</h1>\n<p class="lead">%s</p>\n' % (esc(a["h1"]), esc(a["lead"])))
    o.append('<figure><img src="/images/case-feinschliff.jpg" alt="%s" width="1200" height="750" decoding="async"></figure>\n' % esc(a["img_alt"]))
    o.append(BL.md(a["body"]) + "\n")
    o.append('<div class="post-cta"><h2>%s</h2><p>%s</p><div class="btns"><a class="b1" href="/%s#contact">%s</a><a class="b2" href="/%s#pakete">%s</a></div></div>\n' % (
        esc(u["cta_t"]), esc(u["cta_p"]), B.PATHS[lang], esc(u["cta_b1"]), B.PATHS[lang], esc(u["cta_b2"])))
    o.append('</article>\n</main>\n')
    o.append(BL.tail())
    return "".join(o).replace(" €", " €")


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    for pg in PAGES:
        for lang in ("uk", "ru"):
            if lang not in pg:
                continue
            d = os.path.join(root, B.PATHS[lang])
            os.makedirs(d, exist_ok=True)
            with open(os.path.join(d, pg[lang]["slug"]), "w", encoding="utf-8", newline="\n") as f:
                f.write(render(pg, lang))
            print("ok", lang, pg[lang]["slug"])


if __name__ == "__main__":
    main()
